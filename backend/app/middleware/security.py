"""Small in-process API rate limits and baseline response headers.

The limiter is suitable for a single API worker. Multi-worker or scaled
deployments must enforce equivalent limits at a trusted edge/shared store.
"""

from collections import OrderedDict, deque
from dataclasses import dataclass
import hashlib
import json
import threading
import time
from typing import Callable

from starlette.types import ASGIApp, Message, Receive, Scope, Send


@dataclass(frozen=True)
class RateLimitResult:
    allowed: bool
    remaining: int
    retry_after: int


class SlidingWindowRateLimiter:
    """Thread-safe sliding window limiter with bounded key storage."""

    def __init__(self, max_keys: int = 10_000, clock: Callable[[], float] = time.monotonic):
        self.max_keys = max_keys
        self.clock = clock
        self._windows: OrderedDict[tuple[str, str], deque[float]] = OrderedDict()
        self._lock = threading.Lock()

    def check(self, policy: str, key: str, limit: int, window_seconds: int) -> RateLimitResult:
        now = self.clock()
        cutoff = now - window_seconds
        bucket_key = (policy, key)
        with self._lock:
            events = self._windows.get(bucket_key)
            if events is None:
                events = deque()
                self._windows[bucket_key] = events
            else:
                self._windows.move_to_end(bucket_key)

            while events and events[0] <= cutoff:
                events.popleft()

            if len(events) >= limit:
                retry_after = max(1, int(events[0] + window_seconds - now + 0.999))
                return RateLimitResult(False, 0, retry_after)

            events.append(now)
            while len(self._windows) > self.max_keys:
                self._windows.popitem(last=False)
            return RateLimitResult(True, limit - len(events), 0)

    def clear(self) -> None:
        with self._lock:
            self._windows.clear()


limiter = SlidingWindowRateLimiter()


class SecurityHeadersMiddleware:
    """Ensure baseline headers also cover responses generated by outer CORS."""

    def __init__(self, app: ASGIApp, settings):
        self.app = app
        self.headers = [
            (b"x-content-type-options", b"nosniff"),
            (b"x-frame-options", b"DENY"),
            (b"referrer-policy", b"strict-origin-when-cross-origin"),
            (b"permissions-policy", b"camera=(), microphone=(), geolocation=()"),
        ]
        if settings.APP_ENV.casefold() == "production" and settings.SESSION_COOKIE_SECURE:
            self.headers.append((b"strict-transport-security", b"max-age=63072000; includeSubDomains"))

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        async def send_with_headers(message: Message) -> None:
            if message["type"] == "http.response.start":
                existing = {name.lower() for name, _ in message.get("headers", [])}
                message["headers"] = list(message.get("headers", [])) + [
                    (name, value) for name, value in self.headers if name not in existing
                ]
            await send(message)

        await self.app(scope, receive, send_with_headers)


class SecurityRateLimitMiddleware:
    """Apply API quotas and baseline security headers to ASGI responses."""

    def __init__(self, app: ASGIApp, settings, rate_limiter: SlidingWindowRateLimiter = limiter):
        self.app = app
        self.settings = settings
        self.rate_limiter = rate_limiter

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        headers = [
            (b"x-content-type-options", b"nosniff"),
            (b"x-frame-options", b"DENY"),
            (b"referrer-policy", b"strict-origin-when-cross-origin"),
            (b"permissions-policy", b"camera=(), microphone=(), geolocation=()"),
        ]
        if self.settings.APP_ENV.casefold() == "production" and self.settings.SESSION_COOKIE_SECURE:
            headers.append((b"strict-transport-security", b"max-age=63072000; includeSubDomains"))

        async def send_with_headers(message: Message) -> None:
            if message["type"] == "http.response.start":
                existing = {name.lower() for name, _ in message.get("headers", [])}
                message["headers"] = list(message.get("headers", [])) + [
                    (name, value) for name, value in headers if name not in existing
                ]
            await send(message)

        if not self.settings.RATE_LIMIT_ENABLED or scope.get("method") == "OPTIONS":
            await self.app(scope, receive, send_with_headers)
            return

        path = scope.get("path", "")
        if not path.startswith("/api/") or path in {
            "/api/health", "/api/docs", "/api/openapi.json", "/api/redoc"
        }:
            await self.app(scope, receive, send_with_headers)
            return

        client = scope.get("client")
        ip_address = client[0] if client else "unknown-client"
        cookie_header = next(
            (value.decode("latin-1") for name, value in scope.get("headers", []) if name.lower() == b"cookie"),
            "",
        )
        session_token = ""
        for item in cookie_header.split(";"):
            name, separator, value = item.strip().partition("=")
            if separator and name == self.settings.SESSION_COOKIE_NAME:
                session_token = value
                break
        session_key = hashlib.sha256(session_token.encode("utf-8")).hexdigest() if session_token else ip_address

        method = scope.get("method", "GET").upper()
        specialized = None
        if method == "POST" and path == "/api/resume/upload":
            specialized = (
                "upload",
                ip_address,
                self.settings.RATE_LIMIT_UPLOAD_COUNT,
                self.settings.RATE_LIMIT_UPLOAD_WINDOW_SECONDS,
            )
        elif method == "POST" and (
            path == "/api/improvement/generate"
            or (path.startswith("/api/improvement/") and path.endswith("/rewrite"))
        ):
            specialized = (
                "ai",
                session_key,
                self.settings.RATE_LIMIT_AI_COUNT,
                self.settings.RATE_LIMIT_AI_WINDOW_SECONDS,
            )

        policies = [("api", ip_address, self.settings.RATE_LIMIT_API_PER_MINUTE, 60)]
        if specialized:
            policies.append(specialized)

        for policy, key, limit, window_seconds in policies:
            result = self.rate_limiter.check(policy, key, limit, window_seconds)
            if not result.allowed:
                body = json.dumps({"detail": "Request rate limit exceeded. Please retry later."}).encode()
                await send_with_headers({
                    "type": "http.response.start",
                    "status": 429,
                    "headers": [
                        (b"content-type", b"application/json"),
                        (b"content-length", str(len(body)).encode()),
                        (b"retry-after", str(result.retry_after).encode()),
                        (b"x-ratelimit-limit", str(limit).encode()),
                        (b"x-ratelimit-remaining", b"0"),
                        (b"x-ratelimit-policy", policy.encode()),
                    ],
                })
                await send_with_headers({"type": "http.response.body", "body": body})
                return

        async def send_with_rate_headers(message: Message) -> None:
            if message["type"] == "http.response.start":
                existing = {name.lower() for name, _ in message.get("headers", [])}
                quota_headers = [
                    (b"x-ratelimit-limit", str(policies[-1][2]).encode()),
                    (b"x-ratelimit-remaining", str(result.remaining).encode()),
                ]
                message["headers"] = list(message.get("headers", [])) + [
                    (name, value) for name, value in quota_headers if name not in existing
                ]
            await send_with_headers(message)

        await self.app(scope, receive, send_with_rate_headers)
